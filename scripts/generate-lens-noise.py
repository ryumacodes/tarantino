#!/usr/bin/env python3
"""Generate an original periodic void-and-cluster rank tile for lens sampling.

Deterministic, standard-library-only generation; no external image assets.
Run from any directory. Low-frequency energy is checked against shuffled ranks.
"""
import cmath
import math
from pathlib import Path
import random

SIZE = 32
COUNT = SIZE * SIZE
rng = random.Random(73821)
weights = [(dx, dy, math.exp(-(dx*dx+dy*dy)/(2*1.5**2)))
           for dy in range(-6, 7) for dx in range(-6, 7)]
energy = [0.0] * COUNT
occupied = [False] * COUNT

def toggle(index, present):
    sign = 1 if present else -1
    occupied[index] = present
    x, y = index % SIZE, index // SIZE
    for dx, dy, weight in weights:
        energy[((y+dy) % SIZE)*SIZE+(x+dx) % SIZE] += sign*weight

def cluster():
    return max((i for i in range(COUNT) if occupied[i]), key=lambda i: energy[i])

def void():
    return min((i for i in range(COUNT) if not occupied[i]), key=lambda i: energy[i])

seed_count = COUNT // 10
for i in rng.sample(range(COUNT), seed_count):
    toggle(i, True)
for iteration in range(COUNT*10):
    removed = cluster()
    toggle(removed, False)
    inserted = void()
    toggle(inserted, True)
    if removed == inserted:
        break
else:
    raise RuntimeError('Noise relaxation did not converge')
seed = occupied.copy()
ranks = [0] * COUNT
for rank in reversed(range(seed_count)):
    i = cluster()
    ranks[i] = rank
    toggle(i, False)
for i, present in enumerate(seed):
    if present:
        toggle(i, True)
for rank in range(seed_count, COUNT):
    i = void()
    ranks[i] = rank
    toggle(i, True)
assert sorted(ranks) == list(range(COUNT))

def low_frequency_energy(values):
    total = 0.0
    for ky in range(-3, 4):
        for kx in range(-3, 4):
            if kx == ky == 0:
                continue
            wave = sum((v/(COUNT-1)-0.5)*cmath.exp(-2j*math.pi*
                       (kx*(i % SIZE)+ky*(i//SIZE))/SIZE) for i, v in enumerate(values))
            total += abs(wave)**2
    return total
shuffled = ranks.copy()
rng.shuffle(shuffled)
ratio = low_frequency_energy(ranks)/low_frequency_energy(shuffled)
assert ratio < 0.2, f'Excess low-frequency noise: {ratio}'
output = Path(__file__).resolve().parents[1] / 'src-tauri/src/video_processing/loupe/blue_noise.wgsl'
rows = [', '.join(map(str, ranks[i:i+SIZE])) for i in range(0, COUNT, SIZE)]
output.write_text('// Generated by scripts/generate-lens-noise.py; original periodic rank tile.\n'
                  + 'const lens_noise = array<u32, 1024>(\n    ' + ',\n    '.join(rows) + '\n);\n'
                  + 'fn blue_noise(pixel: vec2<u32>) -> f32 {\n'
                  + '    return f32(lens_noise[(pixel.y % 32u)*32u+pixel.x % 32u])/1024.0;\n}\n')
print(f'Generated {SIZE}x{SIZE} rank tile; low-frequency/white energy ratio {ratio:.6f}')

preview = Path(__file__).resolve().parents[1] / 'src/components/editor/preview/loupeNoise.ts'
preview.write_text('// Generated by scripts/generate-lens-noise.py; original periodic rank tile.\n'
                   + 'export const loupeNoise = new Float32Array([\n    '
                   + ',\n    '.join(rows) + '\n].map(rank => rank / 1024));\n')
